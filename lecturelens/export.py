"""Stage 11 — Export study material as Markdown, PDF (pure-Python fpdf2) and JSON."""

from __future__ import annotations

import logging
import platform
import re
from pathlib import Path

from .utils import fmt_ts, write_json, write_text

log = logging.getLogger(__name__)

BADGE = {"supported": "✓", "uncertain": "?", "unsupported": "⚠"}


def ts_link(source: dict, t: float | None) -> str:
    if t is None:
        return ""
    if source.get("kind") == "youtube" and source.get("video_id"):
        return f"[{fmt_ts(t)}](https://www.youtube.com/watch?v={source['video_id']}&t={int(t)}s)"
    return f"`{fmt_ts(t)}`"


def match_slides_to_headings(notes_md: str, slides: list[dict], min_score: int = 60) -> dict[int, dict]:
    """Line index of each '## heading' -> best-matching slide (title similarity)."""
    try:
        from rapidfuzz import fuzz
    except ImportError:
        return {}
    out, used = {}, set()
    titled = [s for s in slides if s.get("title") and s.get("thumbnail")]
    for i, line in enumerate(notes_md.splitlines()):
        m = re.match(r"^#{2,3}\s+(.*)", line)
        if not m or not titled:
            continue
        heading = m.group(1)
        best = max(titled, key=lambda s: fuzz.token_set_ratio(heading, s["title"]))
        if fuzz.token_set_ratio(heading, best["title"]) >= min_score and best["slide_id"] not in used:
            out[i] = best
            used.add(best["slide_id"])
    return out


def notes_with_thumbnails(notes_md: str, slides: list[dict]) -> str:
    matches = match_slides_to_headings(notes_md, slides)
    lines = notes_md.splitlines()
    out = []
    for i, line in enumerate(lines):
        out.append(line)
        if i in matches:
            s = matches[i]
            out.append(f"\n![Slide {s['slide_id']} at {fmt_ts(s['start'])}]({s['thumbnail']})\n")
    return "\n".join(out)


def to_markdown(result: dict, thumbnails: bool = True) -> str:
    f, src = result["final"], result["source"]
    L = [f"# {f.get('title') or src.get('title')}", ""]
    meta = [f"**Source:** {src.get('title')}"]
    if src.get("kind") == "youtube":
        meta.append(f"[YouTube]({src.get('source')})")
    meta.append(f"**Duration:** {fmt_ts(src.get('duration'))}")
    if result.get("verification", {}).get("faithfulness") is not None:
        meta.append(f"**Faithfulness:** {result['verification']['faithfulness'] * 100:.0f}% of key points supported")
    L += [" · ".join(meta), ""]
    if f.get("extractive_only"):
        L += ["> ⚠ No LLM was available — this is an **extractive** (TextRank) summary.", ""]
    L += ["## Summary", "", f.get("concise_summary", ""), ""]
    if f.get("key_points"):
        L += ["## Key points", ""]
        for kp in f["key_points"]:
            badge = BADGE.get(kp.get("status") or "", "")
            ev = f" _[{kp.get('evidence')}]_" if kp.get("evidence") else ""
            L.append(f"- {badge} {kp['text']} {ts_link(src, kp.get('start'))}{ev}".replace("  ", " "))
            if kp.get("status") == "unsupported":
                L.append("  - ⚠ *Not supported by the transcript/slides — check before relying on it.*")
        L.append("")
    if f.get("detailed_summary"):
        L += ["## Detailed summary", "", f["detailed_summary"], ""]
    if f.get("chapters"):
        L += ["## Chapters", ""]
        L += [f"- {ts_link(src, c.get('start'))} {c['title']}" for c in f["chapters"]]
        L.append("")
    notes = f.get("study_notes_markdown", "")
    if notes:
        notes = re.sub(r"^# .*\n", "", notes)  # we already have a title
        if thumbnails:
            notes = notes_with_thumbnails(notes, result.get("slides", []))
        L += ["# Study notes", "", notes, ""]
    if f.get("glossary"):
        L += ["## Glossary", ""]
        L += [f"- **{g['term']}** — {g.get('definition', '')}" for g in f["glossary"]]
        L.append("")
    rq = f.get("revision_questions") or {}
    if rq.get("mcq") or rq.get("short_answer"):
        L += ["## Revision questions", ""]
        for i, q in enumerate(rq.get("mcq", []), 1):
            L.append(f"**Q{i}.** {q['question']}")
            L += [f"   - {'ABCDEFGH'[j]}) {o}" for j, o in enumerate(q["options"])]
            L.append(f"<details><summary>Answer</summary>{q['answer']} — {q.get('explanation', '')}</details>\n")
        for i, q in enumerate(rq.get("short_answer", []), 1):
            L.append(f"**S{i}.** {q['question']}")
            L.append(f"<details><summary>Model answer</summary>{q['answer']}</details>\n")
    st = result.get("stats", {})
    L += ["---", f"*Generated by LectureLens · transcript: {result.get('transcript_source')} · "
                 f"segmentation: {result.get('segmentation_mode')} · LLM calls: {st.get('llm_calls', 0)} "
                 f"(cache hits {st.get('cache_hits', 0)}) · providers: {', '.join(st.get('providers', [])) or 'none'}*"]
    return "\n".join(L)


