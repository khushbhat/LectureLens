def _find_font() -> tuple[str | None, str | None, str | None]:
    cands = []
    if platform.system() == "Windows":
        cands = [("C:/Windows/Fonts/arial.ttf", "C:/Windows/Fonts/arialbd.ttf", "C:/Windows/Fonts/consola.ttf"),
                 ("C:/Windows/Fonts/segoeui.ttf", "C:/Windows/Fonts/segoeuib.ttf", "C:/Windows/Fonts/cour.ttf")]
    elif platform.system() == "Darwin":
        cands = [("/Library/Fonts/Arial Unicode.ttf", "/Library/Fonts/Arial Unicode.ttf", "/System/Library/Fonts/Menlo.ttc"),
                 ("/System/Library/Fonts/Supplemental/Arial.ttf", "/System/Library/Fonts/Supplemental/Arial Bold.ttf",
                  "/System/Library/Fonts/Supplemental/Courier New.ttf")]
    else:
        cands = [("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
                  "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf")]
    for reg, bold, mono in cands:
        if Path(reg).exists() and Path(bold).exists():
            return reg, bold, mono if Path(mono).exists() and not mono.endswith(".ttc") else None
    return None, None, None


def to_pdf(markdown: str, out_path: Path, run_dir: Path) -> Path:
    from fpdf import FPDF

    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(True, margin=15)
    pdf.set_margins(15, 15, 15)
    reg, bold, mono = _find_font()
    if reg:
        pdf.add_font("Body", "", reg)
        pdf.add_font("Body", "B", bold)
        if mono:
            pdf.add_font("Mono", "", mono)
        body, code_font = "Body", ("Mono" if mono else "Body")
    else:
        body, code_font = "Helvetica", "Courier"

    def clean(t: str) -> str:
        t = re.sub(r"<details><summary>(.*?)</summary>(.*?)</details>", r"\1: \2", t)
        t = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", t)  # links -> text
        if not reg:
            t = t.encode("latin-1", "replace").decode("latin-1")
        else:  # glyphs missing from common fonts
            t = t.replace("✓", "[ok]").replace("⚠", "[!]")
        return t

    pdf.add_page()
    width = pdf.w - pdf.l_margin - pdf.r_margin
    in_code = False
    for raw in markdown.splitlines():
        line = raw.rstrip()
        if line.startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            pdf.set_font(code_font, "", 8.5)
            pdf.set_fill_color(242, 242, 242)
            pdf.multi_cell(width, 4.5, clean(line) or " ", fill=True, new_x="LMARGIN", new_y="NEXT")
            continue
        img = re.match(r"^!\[.*?\]\((.*?)\)", line.strip())
        if img:
            p = run_dir / img.group(1)
            if p.exists():
                try:
                    pdf.image(str(p), w=min(80, width))
                    pdf.ln(2)
                except Exception as e:  # unsupported image: skip
                    log.debug("pdf image skipped: %s", e)
            continue
        h = re.match(r"^(#{1,4})\s+(.*)", line)
        if h:
            size = {1: 17, 2: 14, 3: 12, 4: 11}[len(h.group(1))]
            pdf.ln(2)
            pdf.set_font(body, "B", size)
            pdf.multi_cell(width, size * 0.5, clean(h.group(2)).replace("**", ""), new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1)
            continue
        if not line.strip():
            pdf.ln(2)
            continue
        if line.strip() == "---":
            pdf.ln(2)
            continue
        indent = 0
        b = re.match(r"^(\s*)[-*]\s+(.*)", line)
        if b:
            indent = 4 + min(len(b.group(1)), 6) * 2
            line = "• " + b.group(2)
        pdf.set_font(body, "", 10)
        pdf.set_x(pdf.l_margin + indent)
        txt = clean(line.strip()).replace("`", "")
        try:
            pdf.multi_cell(width - indent, 5, txt, markdown=True, new_x="LMARGIN", new_y="NEXT")
        except Exception:
            pdf.multi_cell(width - indent, 5, txt.replace("**", "").replace("__", ""), new_x="LMARGIN", new_y="NEXT")
    pdf.output(str(out_path))
    return out_path


def export_all(run_dir: Path, result: dict, cfg) -> dict:
    out = {}
    md = to_markdown(result, bool(cfg.get("export.thumbnails_in_notes", True)))
    write_text(run_dir / "lecture.md", md)
    out["markdown"] = str(run_dir / "lecture.md")
    write_json(run_dir / "lecture.json", result)
    out["json"] = str(run_dir / "lecture.json")
    if cfg.get("export.pdf", True):
        try:
            to_pdf(md, run_dir / "lecture.pdf", run_dir)
            out["pdf"] = str(run_dir / "lecture.pdf")
        except Exception as e:
            log.warning("PDF export failed (%s); Markdown/JSON are still available", e)
    return out
